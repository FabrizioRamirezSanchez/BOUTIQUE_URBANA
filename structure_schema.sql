-- 1. Crear la tabla PERSONA
CREATE TABLE persona
(
    IDPER INT GENERATED BY DEFAULT ON NULL AS IDENTITY START WITH 200 INCREMENT BY 1,
    DNIPER CHAR(8),
    NOMPER VARCHAR2(60),
    APEPER VARCHAR2(80),
    EMAPER VARCHAR2(80),
    CELPER CHAR(9),
    TIPPER CHAR(1),
    ESTPER CHAR(1) DEFAULT 'A',
    FECNACPER DATE,
    CONSTRAINT PER_PK PRIMARY KEY (IDPER)
);

-- 2. Crear la tabla CATEGORIA
CREATE TABLE categoria
(
    IDCAT INT GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMCAT VARCHAR2(60),
    CONSTRAINT CAT_PK PRIMARY KEY (IDCAT)
);

-- 3. Crear la tabla PRODUCTO
CREATE TABLE producto
(
    CODPROD CHAR(3),
    NOMPRO VARCHAR2(50),
    IDCAT INTEGER,
    PREPRO NUMBER(8,2),
    STOCKPRO INTEGER,
    ESTPRO CHAR(1),
    CONSTRAINT PROD_PK PRIMARY KEY (CODPROD),
    CONSTRAINT PROD_CAT_FK FOREIGN KEY (IDCAT) REFERENCES categoria (IDCAT)
);

-- 4. Crear la tabla VENTA
CREATE TABLE venta
(
    IDVEN INT GENERATED BY DEFAULT ON NULL AS IDENTITY,
    FECVEN DATE,
    IDCLI INTEGER,
    IDVEND INTEGER,
    TIPPAGVEN CHAR(1),
    ESTVEN CHAR(1),
    CONSTRAINT VEN_PK PRIMARY KEY (IDVEN),
    CONSTRAINT VEN_CLI_FK FOREIGN KEY (IDCLI) REFERENCES persona (IDPER),
    CONSTRAINT VEN_VEND_FK FOREIGN KEY (IDVEND) REFERENCES persona (IDPER)
);

-- 5. Crear la tabla VENTA_DETALLE
CREATE TABLE venta_detalle
(
    IDVENDET INT GENERATED BY DEFAULT ON NULL AS IDENTITY,
    IDVEN INTEGER,
    CODPROD CHAR(3),
    CANVENDET INTEGER,
    CONSTRAINT VENDET_PK PRIMARY KEY (IDVENDET),
    CONSTRAINT VENDET_VEN_FK FOREIGN KEY (IDVEN) REFERENCES venta (IDVEN),
    CONSTRAINT VENDET_PROD_FK FOREIGN KEY (CODPROD) REFERENCES producto (CODPROD)
);



